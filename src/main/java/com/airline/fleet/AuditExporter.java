package com.airline.fleet;

import com.airline.fleet.model.Aircraft;
import com.airline.fleet.model.Flight;
import com.airline.fleet.model.MaintenanceFlag;

import java.io.BufferedWriter;
import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.List;
import java.util.Map;

/**
 * AuditExporter: Generates high-fidelity engineering and compliance audit reports in TXT format.
 * Strictly implements String.format(), substring() manipulations, and structured file export.
 */
public class AuditExporter {

    private final FleetDAO fleetDAO;

    public AuditExporter() {
        this.fleetDAO = new FleetDAO();
    }

    /**
     * Exports a comprehensive fleet maintenance and fuel efficiency audit report to reports/*.txt.
     *
     * @param operatorName Current user / auditor generating the report
     * @return File reference to the saved report
     * @throws Exception if generation or writing fails
     */
    public File generateMaintenanceReport(String operatorName) throws Exception {
        File reportsDir = new File("reports");
        if (!reportsDir.exists()) {
            reportsDir.mkdirs();
        }

        SimpleDateFormat dateFormat = new SimpleDateFormat("yyyyMMdd_HHmmss");
        String timestampStr = dateFormat.format(new Date());
        File outputFile = new File(reportsDir, "fleet_maintenance_report_" + timestampStr + ".txt");

        // Fetch data
        List<Aircraft> aircraftList = fleetDAO.getAllAircraft();
        List<Flight> flightList = fleetDAO.getAllFlights();
        List<MaintenanceFlag> alertList = fleetDAO.getAllMaintenanceFlags();
        Map<String, Object> summary = fleetDAO.getFleetSummaryMetrics();

        try (BufferedWriter writer = new BufferedWriter(new FileWriter(outputFile))) {
            // Header Banner
            writer.write("====================================================================================================\n");
            writer.write("              COMMERCIAL AIRLINE FLEET FUEL EFFICIENCY & MAINTENANCE AUDIT REPORT                   \n");
            writer.write("====================================================================================================\n");
            
            SimpleDateFormat displayFormat = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");
            writer.write(String.format("Generated On   : %s\n", displayFormat.format(new Date())));
            writer.write(String.format("Generated By   : %s\n", operatorName != null ? operatorName : "System Administrator"));
            writer.write(String.format("Classification : ENGINEERING AUDIT & FLIGHT OPERATIONS COMPLIANCE\n"));
            writer.write("====================================================================================================\n\n");

            // Section 1: Executive KPI Summary
            writer.write("----------------------------------------------------------------------------------------------------\n");
            writer.write("1. EXECUTIVE FLEET KPI SUMMARY\n");
            writer.write("----------------------------------------------------------------------------------------------------\n");
            writer.write(String.format("Total Aircraft in Fleet    : %d\n", summary.getOrDefault("totalAircraft", 0)));
            writer.write(String.format("Active Operational Aircraft: %d\n", summary.getOrDefault("activeAircraft", 0)));
            writer.write(String.format("Logged Commercial Flights  : %d\n", summary.getOrDefault("totalFlights", 0)));
            writer.write(String.format("Fleet Average SFC          : %.7f kg_fuel/(kg*km)\n", (Double) summary.getOrDefault("avgSfc", 0.0)));
            writer.write(String.format("Fleet Carbon Intensity     : %.4f kg CO2/ASK (ICAO Emission Baseline: 3.16)\n", (Double) summary.getOrDefault("avgCarbonIntensity", 0.0)));
            writer.write(String.format("Active Maintenance Flags   : %d (Critical: %d)\n", summary.getOrDefault("openAlerts", 0), summary.getOrDefault("criticalAlerts", 0)));
            writer.write("\n");

            // Section 2: Fleet Aircraft Inventory
            writer.write("----------------------------------------------------------------------------------------------------\n");
            writer.write("2. AIRCRAFT INVENTORY & HEALTH STATUS\n");
            writer.write("----------------------------------------------------------------------------------------------------\n");
            writer.write(String.format("%-10s %-24s %-22s %-12s %-12s %-10s\n",
                    "TAIL NO", "MODEL", "CATEGORY", "HOURS", "BASE SFC", "STATUS"));
            writer.write("----------------------------------------------------------------------------------------------------\n");

            for (Aircraft a : aircraftList) {
                // Demonstrate substring() usage: short category display
                String catCode = a.getCategory().name();
                String shortCat = catCode.length() > 20 ? catCode.substring(0, 20) : catCode;

                writer.write(String.format("%-10s %-24s %-22s %10.1f %12.7f %-10s\n",
                        a.getTailNumber(),
                        a.getModel().length() > 24 ? a.getModel().substring(0, 24) : a.getModel(),
                        shortCat,
                        a.getTotalFlightHours(),
                        a.getBaselineSfc(),
                        a.getStatus()));
            }
            writer.write("\n");

            // Section 3: Recent Flight Operations & Efficiency Grading
            writer.write("----------------------------------------------------------------------------------------------------\n");
            writer.write("3. FLIGHT FUEL EFFICIENCY & FLEET GRADING AUDIT\n");
            writer.write("----------------------------------------------------------------------------------------------------\n");
            writer.write(String.format("%-9s %-9s %-9s %-10s %-10s %-12s %-12s %-8s\n",
                    "FLIGHT", "AIRCRAFT", "ROUTE", "DIST(KM)", "FUEL(KG)", "SFC", "CO2/ASK", "GRADE"));
            writer.write("----------------------------------------------------------------------------------------------------\n");

            for (Flight f : flightList) {
                String route = f.getOrigin() + "-" + f.getDestination();
                // Safe substring representation if route is long
                String safeRoute = route.length() > 8 ? route.substring(0, 8) : route;

                writer.write(String.format("%-9s %-9s %-9s %9.0f %9.0f %12.7f %11.4f   %-8s\n",
                        f.getFlightNumber(),
                        f.getAircraftTailNumber() != null ? f.getAircraftTailNumber() : "ID:" + f.getAircraftId(),
                        safeRoute,
                        f.getDistanceKm(),
                        f.getTotalFuelBurnedKg(),
                        f.getCalculatedSfc(),
                        f.getCarbonIntensity(),
                        f.getFleetGrade() != null ? f.getFleetGrade().name() : "N/A"));
            }
            writer.write("\n");

            // Section 4: Engine Vibration & Maintenance Alerts
            writer.write("----------------------------------------------------------------------------------------------------\n");
            writer.write("4. ENGINE VIBRATION MONITORING & MAINTENANCE ALERT LOG\n");
            writer.write("----------------------------------------------------------------------------------------------------\n");
            writer.write(String.format("%-6s %-10s %-10s %-10s %-8s %-12s %-38s\n",
                    "ID", "TAIL", "FLIGHT", "SEVERITY", "VIB(MIL)", "STATUS", "ANOMALY DESCRIPTION"));
            writer.write("----------------------------------------------------------------------------------------------------\n");

            if (alertList.isEmpty()) {
                writer.write("   >> No active or historical maintenance flags recorded. Fleet operating within nominal limits.\n");
            } else {
                for (MaintenanceFlag m : alertList) {
                    String desc = m.getDescription();
                    String shortDesc = (desc != null && desc.length() > 38) ? desc.substring(0, 35) + "..." : (desc != null ? desc : "");
                    String vibStr = m.getVibrationReadingMils() != null ? String.format("%.2f", m.getVibrationReadingMils()) : "-";

                    writer.write(String.format("%-6d %-10s %-10s %-10s %-8s %-12s %-38s\n",
                            m.getFlagId(),
                            m.getAircraftTailNumber() != null ? m.getAircraftTailNumber() : "ID:" + m.getAircraftId(),
                            m.getFlightNumber() != null ? m.getFlightNumber() : "-",
                            m.getSeverity(),
                            vibStr,
                            m.getStatus(),
                            shortDesc));
                }
            }
            writer.write("\n");

            // Audit Conclusion and Sign-off
            writer.write("====================================================================================================\n");
            writer.write("AUDIT SIGN-OFF:\n");
            writer.write("Vibration Safety Limits: Normal < 2.5 mils | Caution: 2.5 - 4.0 mils | Critical: > 4.0 mils\n");
            writer.write("Fuel Efficiency Grading: A (<= 0.000038) | B (<= 0.000048) | C (> 0.000048) | Outlier (> +25%)\n");
            writer.write("CO2 Emission Constant  : 3.16 kg CO2/kg Jet-A fuel (ICAO Annex 16 Vol IV Standard)\n");
            writer.write("Chief Engineer Signature: ___________________________    Date: __________________\n");
            writer.write("====================================================================================================\n");
        }

        return outputFile;
    }
}
